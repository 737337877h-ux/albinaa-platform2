-- Run as the IAS20261 owner or a DBA for ALBINAA20261PAYWRITER.
-- Adds only the minimum privileges needed to validate and insert an unapproved
-- payment request (GLST018). No receipt, journal, posting, approval-decision,
-- UPDATE, DELETE, ALTER, or EXECUTE privilege is granted.

GRANT CREATE SESSION TO ALBINAA20261PAYWRITER;

GRANT SELECT, INSERT ON IAS20261.IAS_RQ_VCHR_MST TO ALBINAA20261PAYWRITER;
GRANT SELECT, INSERT ON IAS20261.IAS_RQ_VCHR_DTL TO ALBINAA20261PAYWRITER;
GRANT INSERT ON IAS20261.S_APPRVD_MOV TO ALBINAA20261PAYWRITER;
GRANT SELECT ON IAS20261.IAS_DOC_SEQ_OTHR TO ALBINAA20261PAYWRITER;

GRANT SELECT ON IAS20261.EX_RATE TO ALBINAA20261PAYWRITER;
GRANT SELECT ON IAS20261.IAS_PERIOD_EX_RATE_DAY TO ALBINAA20261PAYWRITER;

GRANT SELECT ON IAS20261.PRIV_CASH TO ALBINAA20261PAYWRITER;
GRANT SELECT ON IAS20261.CASH_IN_HAND TO ALBINAA20261PAYWRITER;
GRANT SELECT ON IAS20261.CASH_AT_BANK TO ALBINAA20261PAYWRITER;
GRANT SELECT ON IAS20261.ACCOUNT_CURR TO ALBINAA20261PAYWRITER;
GRANT SELECT ON IAS20261.CUSTOMER_CURR TO ALBINAA20261PAYWRITER;

GRANT SELECT ON IAS20261.GLS_ACCNT_DTL TO ALBINAA20261PAYWRITER;
GRANT SELECT ON IAS20261.COLLERCTOR TO ALBINAA20261PAYWRITER;

SELECT TABLE_NAME, PRIVILEGE
FROM DBA_TAB_PRIVS
WHERE GRANTEE = 'ALBINAA20261PAYWRITER'
  AND OWNER = 'IAS20261'
ORDER BY TABLE_NAME, PRIVILEGE;
