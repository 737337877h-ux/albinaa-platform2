function Get-OracleCustomerQueries {
  return @(
    [pscustomobject]@{
      Name = 'customers'; FileName = 'customers.csv'; Sql = @"
SELECT C_CODE,C_A_CODE,C_A_NAME,C_PHONE,C_MOBILE,C_ADDRESS,R_CODE,
 LATITUDE,LONGITUDE,TO_CHAR(C_SINCE,'YYYY-MM-DD') C_SINCE,
 NVL(INACTIVE,0) INACTIVE,CONN_BRN_NO,COL_NO,
 TO_CHAR(AD_DATE,'YYYY-MM-DD HH24:MI:SS') AD_DATE,
 TO_CHAR(UP_DATE,'YYYY-MM-DD HH24:MI:SS') UP_DATE
FROM IAS20261.CUSTOMER
ORDER BY C_CODE
"@
    },
    [pscustomobject]@{
      Name = 'customer_currencies'; FileName = 'customer_currencies.csv'; Sql = @"
SELECT C_CODE,A_CY,NVL(INACTIVE,0) INACTIVE,
 NVL(CR_LIMIT,0) CR_LIMIT,NVL(INV_LIMIT,0) INV_LIMIT
FROM IAS20261.CUSTOMER_CURR
ORDER BY C_CODE,A_CY
"@
    },
    [pscustomobject]@{
      Name = 'customer_balances'; FileName = 'customer_balances.csv'; Sql = @"
SELECT C_CODE,A_CY,COUNT(*) TRANSACTION_COUNT,
 ROUND(SUM(CASE WHEN DOC_TYPE=0 THEN NVL(DR_AMT,0) ELSE 0 END),16) OPENING_DEBIT_LOCAL,
 ROUND(SUM(CASE WHEN DOC_TYPE=0 THEN NVL(CR_AMT,0) ELSE 0 END),16) OPENING_CREDIT_LOCAL,
 ROUND(SUM(NVL(DR_AMT,0)-NVL(CR_AMT,0)),16) BALANCE_LOCAL,
 ROUND(SUM(CASE WHEN DOC_TYPE=0 THEN NVL(DR_AMTF,0) ELSE 0 END),16) OPENING_DEBIT_FOREIGN,
 ROUND(SUM(CASE WHEN DOC_TYPE=0 THEN NVL(CR_AMTF,0) ELSE 0 END),16) OPENING_CREDIT_FOREIGN,
 ROUND(SUM(NVL(DR_AMTF,0)-NVL(CR_AMTF,0)),16) BALANCE_FOREIGN,
 TO_CHAR(MIN(DOC_DATE),'YYYY-MM-DD') FIRST_TRANSACTION_DATE,
 TO_CHAR(MAX(DOC_DATE),'YYYY-MM-DD') LAST_TRANSACTION_DATE
FROM IAS20261.IAS_V_CST_TRNS
GROUP BY C_CODE,A_CY
ORDER BY C_CODE,A_CY
"@
    },
    [pscustomobject]@{
      Name = 'control_reconciliation'; FileName = 'control_reconciliation.csv'; Sql = @"
SELECT X.A_CODE,X.A_CY,X.CUSTOMER_COUNT,
 X.CUSTOMER_BALANCE_LOCAL,A.CRNT_BLNC_L,
 (X.CUSTOMER_BALANCE_LOCAL-A.CRNT_BLNC_L) DIFFERENCE_LOCAL,
 X.CUSTOMER_BALANCE_FOREIGN,A.CRNT_BLNC_F,
 (X.CUSTOMER_BALANCE_FOREIGN-A.CRNT_BLNC_F) DIFFERENCE_FOREIGN
FROM (
 SELECT C.C_A_CODE A_CODE,T.A_CY,COUNT(DISTINCT T.C_CODE) CUSTOMER_COUNT,
  SUM(NVL(T.DR_AMT,0)-NVL(T.CR_AMT,0)) CUSTOMER_BALANCE_LOCAL,
  SUM(NVL(T.DR_AMTF,0)-NVL(T.CR_AMTF,0)) CUSTOMER_BALANCE_FOREIGN
 FROM IAS20261.IAS_V_CST_TRNS T
 JOIN IAS20261.CUSTOMER C ON C.C_CODE=T.C_CODE
 GROUP BY C.C_A_CODE,T.A_CY
) X
LEFT JOIN IAS20261.IAS_V_ACCNT_BLNC A ON A.A_CODE=X.A_CODE AND A.A_CY=X.A_CY
ORDER BY X.A_CODE,X.A_CY
"@
    },
    [pscustomobject]@{
      Name = 'control_totals'; FileName = 'control_totals.csv'; Sql = @"
SELECT
 (SELECT COUNT(*) FROM IAS20261.CUSTOMER) CUSTOMERS,
 (SELECT COUNT(*) FROM IAS20261.CUSTOMER_CURR) CUSTOMER_CURRENCIES,
 (SELECT COUNT(*) FROM (SELECT C_CODE,A_CY FROM IAS20261.IAS_V_CST_TRNS GROUP BY C_CODE,A_CY)) CUSTOMER_BALANCES,
 (SELECT COUNT(*) FROM IAS20261.IAS_V_CST_TRNS) TRANSACTION_ROWS
FROM DUAL
"@
    }
  )
}
