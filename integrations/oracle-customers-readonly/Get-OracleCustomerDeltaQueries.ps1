function Get-OracleCustomerDeltaQueries {
  return @(
    [pscustomobject]@{
      Name = 'customer_transactions_since_20260813'; FileName = 'customer_transactions_since_20260813.csv'; Sql = @"
SELECT C_CODE,A_CY,TO_CHAR(DOC_DATE,'YYYY-MM-DD') DOC_DATE,
 DOC_TYPE,DOC_JV_TYPE,DOC_NO,DOC_SER,RCRD_NO,REF_NO,DOC_DESC,
 NVL(DR_AMT,0) DR_AMT,NVL(CR_AMT,0) CR_AMT,
