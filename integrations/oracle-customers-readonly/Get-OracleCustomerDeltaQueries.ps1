    [pscustomobject]@{
      Name = 'delta_control_totals'; FileName = 'delta_control_totals.csv'; Sql = @"
SELECT COUNT(*) TRANSACTION_ROWS,COUNT(DISTINCT C_CODE) CUSTOMER_COUNT,
 MIN(TO_CHAR(DOC_DATE,'YYYY-MM-DD')) FIRST_DATE,
 MAX(TO_CHAR(DOC_DATE,'YYYY-MM-DD')) LAST_DATE
FROM IAS20261.IAS_V_CST_TRNS
WHERE DOC_DATE >= TO_DATE('2026-08-13','YYYY-MM-DD')
