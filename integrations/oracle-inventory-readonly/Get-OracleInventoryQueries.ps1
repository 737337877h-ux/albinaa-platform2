function Get-OracleInventoryQueries {
  return @(
    [pscustomobject]@{
      Name = 'item_groups'; FileName = 'item_groups.csv'; Sql = @"
SELECT G_CODE,G_A_NAME,G_E_NAME,G_I_CODE,
 TO_CHAR(UP_DATE,'YYYY-MM-DD HH24:MI:SS') UP_DATE
FROM IAS20261.GROUP_DETAILS
ORDER BY G_CODE
"@
    },
    [pscustomobject]@{
      Name = 'items'; FileName = 'items.csv'; Sql = @"
SELECT I_CODE,I_NAME,G_CODE,PRIMARY_COST,I_CWTAVG,
 NVL(INACTIVE,0) INACTIVE,NVL(SERVICE_ITM,0) SERVICE_ITM,
 TO_CHAR(UP_DATE,'YYYY-MM-DD HH24:MI:SS') UP_DATE
FROM IAS20261.IAS_ITM_MST
ORDER BY I_CODE
"@
    },
    [pscustomobject]@{
      Name = 'item_units'; FileName = 'item_units.csv'; Sql = @"
SELECT D.I_CODE,D.ITM_UNT,D.P_SIZE,NVL(D.MAIN_UNIT,0) MAIN_UNIT,
 NVL(SALE_UNIT,0) SALE_UNIT,NVL(PUR_UNIT,0) PUR_UNIT,
 NVL(STOCK_UNIT,0) STOCK_UNIT,NVL(PRICE_UNIT,0) PRICE_UNIT,
 NVL(NO_SALE,0) NO_SALE,BARCODE,LVL_UNIT,NVL(USE_SRLNO,0) USE_SRLNO,
 NVL(INACTIVE,0) INACTIVE,INACTIVE_RES,
 (SELECT MAX(P.I_PRICE) FROM IAS20261.IAS_V_ITM_AVLQTY P
   WHERE P.I_CODE=D.I_CODE AND P.ITM_UNT=D.ITM_UNT) SALE_PRICE,
 TO_CHAR(D.UP_DATE,'YYYY-MM-DD HH24:MI:SS') UP_DATE
FROM IAS20261.IAS_ITM_DTL D
ORDER BY D.I_CODE,D.LVL_UNIT,D.P_SIZE,D.ITM_UNT
"@
    },
    [pscustomobject]@{
      Name = 'warehouse_groups'; FileName = 'warehouse_groups.csv'; Sql = @"
SELECT WHG_CODE,WHG_A_NAME,WHG_E_NAME,
 TO_CHAR(UP_DATE,'YYYY-MM-DD HH24:MI:SS') UP_DATE
FROM IAS20261.WAREHOUSE_GROUP
ORDER BY WHG_CODE
"@
    },
    [pscustomobject]@{
      Name = 'warehouses'; FileName = 'warehouses.csv'; Sql = @"
SELECT W_CODE,W_NAME,W_E_NAME,LOCATION,TEL_NO,NVL(INACTIVE,0) INACTIVE,
 WH_KEEPER,WHG_CODE,W_TYPE,NVL(NO_SALE,0) NO_SALE,
 NVL(CHK_AVL_QTY,0) CHK_AVL_QTY,CONN_BRN_NO,MAIN_WCODE,LATITUDE,LONGITUDE,
 TO_CHAR(UP_DATE,'YYYY-MM-DD HH24:MI:SS') UP_DATE
FROM IAS20261.WAREHOUSE_DETAILS
ORDER BY W_CODE
"@
    },
    [pscustomobject]@{
      Name = 'stock_balances'; FileName = 'stock_balances.csv'; Sql = @"
SELECT I_CODE,ITM_UNT,P_SIZE,W_CODE,WHG_CODE,NVL(AVL_QTY,0) AVL_QTY,
 PRIMARY_COST,I_CWTAVG,NVL(INACTIVE,0) INACTIVE,
 TO_CHAR(UP_DATE,'YYYY-MM-DD HH24:MI:SS') UP_DATE
FROM IAS20261.IAS_ITM_WCODE
ORDER BY W_CODE,I_CODE,ITM_UNT,P_SIZE,WHG_CODE
"@
    },
    [pscustomobject]@{
      Name = 'control_totals'; FileName = 'control_totals.csv'; Sql = @"
SELECT
 (SELECT COUNT(*) FROM IAS20261.GROUP_DETAILS) ITEM_GROUPS,
 (SELECT COUNT(*) FROM IAS20261.IAS_ITM_MST) ITEMS,
 (SELECT COUNT(*) FROM IAS20261.IAS_ITM_DTL) ITEM_UNITS,
 (SELECT COUNT(*) FROM IAS20261.WAREHOUSE_GROUP) WAREHOUSE_GROUPS,
 (SELECT COUNT(*) FROM IAS20261.WAREHOUSE_DETAILS) WAREHOUSES,
 (SELECT COUNT(*) FROM IAS20261.IAS_ITM_WCODE) STOCK_BALANCE_ROWS
FROM IAS20261.S_CMPNY
WHERE ROWNUM=1
"@
    }
  )
}
