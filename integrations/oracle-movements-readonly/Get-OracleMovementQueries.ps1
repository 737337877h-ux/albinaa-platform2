function Get-OracleMovementQueries {
  return @(
    [pscustomobject]@{
      Name = 'customer_movements'; FileName = 'customer_movements.csv'; Sql = @"
SELECT C_CODE,A_CY,TO_CHAR(DOC_DATE,'YYYY-MM-DD') DOC_DATE,
 DOC_TYPE,DOC_JV_TYPE,DOC_NO,DOC_SER,RCRD_NO,REF_NO,DOC_DESC,
 NVL(DR_AMT,0) DR_AMT,NVL(CR_AMT,0) CR_AMT,
 NVL(DR_AMTF,0) DR_AMTF,NVL(CR_AMTF,0) CR_AMTF,
 TO_CHAR(AD_DATE,'YYYY-MM-DD HH24:MI:SS') AD_DATE,
 TO_CHAR(UP_DATE,'YYYY-MM-DD HH24:MI:SS') UP_DATE,TO_CHAR(COL_NO) COL_NO
FROM IAS20261.IAS_V_CST_TRNS
ORDER BY DOC_DATE,C_CODE,A_CY,DOC_TYPE,DOC_JV_TYPE,DOC_NO,DOC_SER,RCRD_NO,
 NVL(REF_NO,' '),NVL(DR_AMT,0),NVL(CR_AMT,0),NVL(DR_AMTF,0),NVL(CR_AMTF,0)
"@
    },
    [pscustomobject]@{
      Name = 'inventory_movements'; FileName = 'inventory_movements.csv'; Sql = @"
SELECT DOC_TYPE,BILL_DOC_TYPE,DOC_NO,I_CODE,NVL(I_QTY,0) I_QTY,
 NVL(FREE_QTY,0) FREE_QTY,ITM_UNT,P_SIZE,NVL(P_QTY,0) P_QTY,
 NVL(PF_QTY,0) PF_QTY,TO_CHAR(I_DATE,'YYYY-MM-DD') I_DATE,
 I_COST,W_CODE,WHG_CODE,STK_COST,A_CY,C_CODE,V_CODE,A_DESC,
 RCRD_NO,SERIAL,REF_NO,DOC_SER,DOC_SEQUENCE,BARCODE,IN_OUT,
 TO_CHAR(AD_DATE,'YYYY-MM-DD HH24:MI:SS') AD_DATE,
 TO_CHAR(UP_DATE,'YYYY-MM-DD HH24:MI:SS') UP_DATE,
 CMP_NO,BRN_NO,BRN_YEAR
FROM IAS20261.ITEM_MOVEMENT
ORDER BY I_DATE,DOC_TYPE,DOC_SER,DOC_NO,DOC_SEQUENCE,SERIAL,RCRD_NO,
 I_CODE,W_CODE,ITM_UNT,P_SIZE
"@
    },
    [pscustomobject]@{
      Name = 'control_totals'; FileName = 'control_totals.csv'; Sql = @"
SELECT
 (SELECT COUNT(*) FROM IAS20261.IAS_V_CST_TRNS) CUSTOMER_MOVEMENTS,
 (SELECT COUNT(*) FROM IAS20261.IAS_V_CST_TRNS WHERE RCRD_NO IS NULL) CUSTOMER_MISSING_RCRD_NO,
 (SELECT COUNT(*) FROM IAS20261.IAS_V_CST_TRNS WHERE UP_DATE IS NULL) CUSTOMER_MISSING_UP_DATE,
 (SELECT COUNT(*) FROM IAS20261.ITEM_MOVEMENT) INVENTORY_MOVEMENTS,
 (SELECT COUNT(*) FROM IAS20261.ITEM_MOVEMENT WHERE RCRD_NO IS NULL) INVENTORY_MISSING_RCRD_NO,
 (SELECT COUNT(*) FROM IAS20261.ITEM_MOVEMENT WHERE UP_DATE IS NULL) INVENTORY_MISSING_UP_DATE
FROM DUAL
"@
    }
  )
}
